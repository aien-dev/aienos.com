#!/bin/sh
# Verification-only host tool. Emits om/site/verify-unicode.om, the Unicode
# class tables the Omega verifier needs to reproduce the Rust oracle's regex
# semantics exactly: \w (and therefore \b), \d and \s of the regex crate are
# Unicode classes taken from regex-syntax's generated tables. This script
# copies those tables, it does not compute them; the oracle's own crate
# source is the authority.
#
#   sh om/site/verify-unicode.sh [REGEX_SYNTAX_SRC] > om/site/verify-unicode.om
#   sh om/site/verify-unicode.sh --check [REGEX_SYNTAX_SRC]   # exit 1 on drift
#
# Default source: the newest regex-syntax 0.8.x in ~/.cargo/registry, which is
# what `regex = "1"` in crates/site-builder/Cargo.toml resolves to (no lock file
# is committed). The emitted header records the version and Unicode version.
set -eu
check=0
if [ "${1:-}" = "--check" ]; then check=1; shift; fi
src=${1:-}
if [ -z "$src" ]; then
    src=$(ls -d "$HOME"/.cargo/registry/src/*/regex-syntax-0.8.* 2>/dev/null | sort -V | tail -n 1)
fi
tables="$src/src/unicode_tables"
for f in perl_word perl_decimal perl_space; do
    [ -f "$tables/$f.rs" ] || { echo "verify-unicode: missing $tables/$f.rs" >&2; exit 2; }
done
gen() {
    python3 - "$tables" "$(basename "$src")" <<'PY'
import ast, re, sys
tables, version = sys.argv[1], sys.argv[2]
def ranges(name):
    text = open(f"{tables}/{name}.rs", encoding="utf-8").read()
    uni = re.search(r"Unicode version: ([0-9]+(?:\.[0-9]+)*)", text).group(1)
    body = text[text.index("&[", text.index("pub const", text.index("BY_NAME") if "BY_NAME" in text else 0)):]
    out = []
    for a, b in re.findall(r"\('((?:\\.|[^'\\])+)', '((?:\\.|[^'\\])+)'\)", body):
        out.append((code(a), code(b)))
    return uni, out
def code(lit):
    m = re.fullmatch(r"\\u\{([0-9a-fA-F]+)\}", lit)
    if m:
        return int(m.group(1), 16)
    value = ast.literal_eval("'" + lit + "'")
    assert len(value) == 1, lit
    return ord(value)
rows = []
for name, tag in (("perl_word", "vuw"), ("perl_decimal", "vud"), ("perl_space", "vus")):
    uni, rs = ranges(name)
    for lo, hi in rs:
        assert lo <= hi
    for (a, b), (c, d) in zip(rs, rs[1:]):
        assert b < c, (name, a, b, c, d)
    rows.append((tag, name, uni, rs))
print("note GENERATED by om/site/verify-unicode.sh from " + version + " src/unicode_tables; do not edit.")
for tag, name, uni, rs in rows:
    print(f"note {tag}: {name}.rs, Unicode {uni}, {len(rs)} ranges as decimal lo hi pairs.")
for tag, name, uni, rs in rows:
    print(f"const {tag.upper()}N ulong {len(rs)}")
for tag, name, uni, rs in rows:
    print(f'text {tag} "' + " ".join(f"{lo} {hi}" for lo, hi in rs) + '"')
PY
}
if [ "$check" -eq 1 ]; then
    here=$(dirname "$0")
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' EXIT
    gen > "$tmp"
    if cmp -s "$tmp" "$here/verify-unicode.om"; then echo "verify-unicode: tables match $src"; exit 0; fi
    echo "verify-unicode: om/site/verify-unicode.om differs from $src" >&2
    exit 1
fi
gen
