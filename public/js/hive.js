/* Seeded Omega freshness decision; JS remains the explicit load-failure fallback. */
(() => {
  'use strict';
  const hive = document.getElementById('hive');
  if (!hive) return;
  let wasmFresh = null;
  function jsFresh(nowMs, generatedMs, previousMs, staleAfterMs, fetchOk) {
    if (generatedMs < previousMs) return 2;
    if (!fetchOk) return 3;
    return Math.max(0, nowMs - generatedMs) > staleAfterMs ? 1 : 0;
  }
  window.hiveFresh = (nowMs, generatedMs, previousMs, staleAfterMs, fetchOk) => {
    // Date timestamps and thresholds are integers; ceil preserves strict > for elapsed fractions.
    const values = [Math.ceil(nowMs), generatedMs, previousMs, staleAfterMs];
    const useWasm = wasmFresh && values.every(Number.isSafeInteger);
    hive.dataset.freshEngine = useWasm ? 'wasm' : 'js';
    const state = useWasm
      ? wasmFresh(...values.map(BigInt), fetchOk ? 1 : 0)
      : jsFresh(nowMs, generatedMs, previousMs, staleAfterMs, fetchOk);
    hive.dataset.freshState = String(state);
    return state;
  };
  window.hiveFreshReady = (async () => {
    try {
      const response = await fetch('/wasm/hive-fresh.wasm', { cache: 'no-cache', credentials: 'omit' });
      if (!response.ok) throw new Error('Freshness module unavailable');
      const fallback = response.clone();
      let compiled;
      try {
        compiled = await WebAssembly.instantiateStreaming(response);
      } catch (_) {
        compiled = await WebAssembly.instantiate(await fallback.arrayBuffer());
      }
      if (typeof compiled.instance.exports.fresh !== 'function') throw new Error('Freshness export unavailable');
      wasmFresh = compiled.instance.exports.fresh;
      return true;
    } catch (_) {
      wasmFresh = null;
      return false;
    }
  })();
})();
/* Generated by om/hive-page/hive-js.om. Never edit this artifact.
 * Only same-origin edge-rendered HTML enters DOMParser; never render JSON here. */
(() => {
  'use strict';
  const page = document.getElementById('hive');
  if (!page) return;
  const get = id => document.getElementById(id);
  const tree = get('hive-tree'), chat = get('hive-chat'), search = get('hive-search');
  const store = get('hive-manifest-cards'), panel = get('hive-manifest-body');
  let selected = new URLSearchParams(location.hash.slice(1)).get('agent');
  let scope = 'all', query = '', board = null, connected = false, regressed = false;
  let advancedAt = 0, sourceAge = 0, trusted = false, active = false;
  let searchOpen = null;
  const say = (id, value) => { const node = get(id); if (node && node.textContent !== value) node.textContent = value; };

  // Patch in place. Id-keyed nodes survive reordering; unkeyed structure is paired
  // positionally. A stack avoids recursion through deeply nested mission trees.
  function morph(target, source) {
    const work = [[target, source]];
    while (work.length) {
      const [old, fresh] = work.pop();
      if (old.isEqualNode(fresh)) continue;
      if (old.nodeType !== fresh.nodeType || old.nodeName !== fresh.nodeName) { old.replaceWith(fresh.cloneNode(true)); continue; }
      if (old.nodeType !== Node.ELEMENT_NODE) { old.nodeValue = fresh.nodeValue; continue; }
      const preserve = name => (old.tagName === 'DETAILS' && name === 'open') || name === 'hidden' || name === 'data-selected';
      for (const attr of [...old.attributes]) if (!preserve(attr.name) && !fresh.hasAttribute(attr.name)) old.removeAttribute(attr.name);
      for (const attr of fresh.attributes) if (!preserve(attr.name) && old.getAttribute(attr.name) !== attr.value) old.setAttribute(attr.name, attr.value);
      const keyed = new Map([...old.childNodes].filter(node => node.id).map(node => [node.id, node]));
      const wanted = new Set();
      let at = old.firstChild;
      for (const child of fresh.childNodes) {
        let node = child.id ? keyed.get(child.id) : at && !at.id && at.nodeName === child.nodeName ? at : null;
        if (!node) node = child.cloneNode(true);
        if (node !== at) old.insertBefore(node, at);
        wanted.add(node);
        work.push([node, child]);
        at = node.nextSibling;
      }
      for (const child of [...old.childNodes]) if (!wanted.has(child)) child.remove();
    }
  }

  function filters() {
    const visible = new Set();
    let hits = 0;
    for (const row of tree.querySelectorAll('.hive-node')) {
      const id = row.id.slice(5), card = get('manifest-' + id);
      const matches = !query || (row.querySelector('summary')?.textContent + ' ' + card?.textContent).toLowerCase().includes(query);
      if (matches) {
        hits += 1;
        for (let up = row; up && up !== tree; up = up.parentElement) {
          if (up.matches('.hive-node')) visible.add(up);
          if (query && up.tagName === 'DETAILS') up.open = true;
        }
      }
    }
    for (const row of tree.querySelectorAll('.hive-node')) row.hidden = !visible.has(row);
    say('hive-search-count', query ? `${hits} matching agents` : '');
    for (const item of chat.children) item.hidden = scope === 'selected' && item.dataset.agent !== selected;
    get('hive-chat-all').setAttribute('aria-pressed', String(scope === 'all'));
    get('hive-chat-selected').setAttribute('aria-pressed', String(scope === 'selected'));
  }

  function choose(id, fragment = true, reveal = true) {
    if (panel.firstElementChild) store.append(panel.firstElementChild);
    const card = get('manifest-' + id), row = get('node-' + id);
    selected = id;
    panel.hidden = !card;
    get('hive-manifest-empty').hidden = Boolean(card);
    if (card) { card.open = true; panel.append(card); }
    for (const item of tree.querySelectorAll('.hive-node')) item.dataset.selected = String(item === row);
    if (row && reveal) for (let up = row.parentElement; up && up !== tree; up = up.parentElement) if (up.tagName === 'DETAILS') up.open = true;
    if (fragment && row) { try { history.replaceState(null, '', '#agent=' + encodeURIComponent(id)); } catch (_) {} }
    filters();
  }

  function freshness() {
    if (!board) { page.dataset.fresh = 'false'; return; }
    const elapsed = Math.max(0, performance.now() - advancedAt);
    const state = window.hiveFresh(sourceAge + elapsed, 0, regressed ? 1 : 0, Number(board.dataset.staleAfter), connected);
    const stale = state === 1;
    page.dataset.fresh = String(connected && !stale && trusted);
    say('hive-connection', !connected ? regressed ? 'Snapshot timestamp moved backwards; last observation retained' : 'Connection interrupted; last snapshot retained' : stale ? 'Source stale; last observation retained' : !trusted ? 'Connected; source age not verified' : 'Receiving source observations');
    say('hive-freshness', `${Math.floor(elapsed / 1000)}s since the source timestamp advanced. Last observation retained on interruption.`);
  }

  function ingest(markup, serverDate) {
    const document = new DOMParser().parseFromString(markup, 'text/html');
    const incoming = document.getElementById('hive-board');
    const generated = Date.parse(incoming?.dataset.generated || '');
    if (!incoming || !Number.isFinite(generated) || incoming.dataset.staleAfter !== '15000' || !incoming.dataset.sequence || incoming.dataset.sequence.length > 128) throw new Error('Invalid edge board');
    if (board && window.hiveFresh(generated, generated, Date.parse(board.dataset.generated), Number(incoming.dataset.staleAfter), true) === 2) { regressed = true; throw new Error('Snapshot moved backwards'); }
    for (const id of ['hive-tree', 'hive-chat', 'hive-manifest-cards', 'hive-source-time', 'hive-counts', 'hive-coverage']) if (!incoming.querySelector('#' + id)) throw new Error('Incomplete edge board');
    if (!board || generated > Date.parse(board.dataset.generated)) {
      advancedAt = performance.now();
      const server = Date.parse(serverDate || '');
      trusted = Number.isFinite(server) && generated <= server + 2000;
      sourceAge = trusted ? Math.max(0, server - generated) : 0;
      regressed = false;
    }
    const focused = window.document.activeElement;
    const scroll = [chat.scrollTop, tree.parentElement.scrollTop, panel.parentElement.scrollTop];
    if (panel.firstElementChild) store.append(panel.firstElementChild);
    for (const id of ['hive-tree', 'hive-chat', 'hive-manifest-cards', 'hive-source-time', 'hive-counts', 'hive-coverage']) morph(get(id), incoming.querySelector('#' + id));
    board = incoming;
    for (const name of ['generated', 'sequence', 'staleAfter']) page.dataset[name] = incoming.dataset[name];
    connected = true;
    get('hive-tree-empty').hidden = tree.children.length > 0;
    get('hive-chat-empty').hidden = chat.children.length > 0;
    say('hive-fetch-time', new Date().toISOString());
    choose(selected, false, false);
    [chat.scrollTop, tree.parentElement.scrollTop, panel.parentElement.scrollTop] = scroll;
    if (focused?.isConnected && window.document.activeElement !== focused) focused.focus({ preventScroll: true });
    freshness();
  }

  async function poll() {
    if (active) return;
    active = true;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4500);
    try {
      const response = await fetch('/hive/board/', { cache: 'no-store', credentials: 'omit', signal: controller.signal, headers: { Accept: 'text/html' } });
      if (!response.ok || !response.headers.get('content-type')?.toLowerCase().includes('text/html')) throw new Error('Board unavailable');
      ingest(await response.text(), response.headers.get('date'));
    } catch (_) {
      connected = false;
      if (!board) say('hive-connection', 'Telemetry unavailable; no source observation received');
      freshness();
    } finally { clearTimeout(timeout); active = false; }
  }

  search.addEventListener('input', () => {
    query = search.value.trim().toLowerCase();
    if (query && !searchOpen) searchOpen = new Map([...tree.querySelectorAll('details[id]')].map(node => [node.id, node.open]));
    if (!query && searchOpen) { for (const [id, open] of searchOpen) { const node = get(id); if (node) node.open = open; } searchOpen = null; }
    filters();
  });
  tree.addEventListener('click', event => { const link = event.target.closest('a[data-agent]'); if (link) { event.preventDefault(); choose(link.dataset.agent); } });
  get('hive-chat-all').addEventListener('click', () => { scope = 'all'; filters(); });
  get('hive-chat-selected').addEventListener('click', () => { scope = 'selected'; filters(); });
  addEventListener('hashchange', () => choose(new URLSearchParams(location.hash.slice(1)).get('agent'), false));
  setInterval(freshness, 1000);
  setInterval(poll, 1000);
  poll();
})();
